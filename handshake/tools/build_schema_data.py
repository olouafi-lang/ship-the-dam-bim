"""Generate schema-data.js from ifcopenshell's bundled IFC schemas.

For each schema we record every entity name and its direct supertype, so the
browser can (a) tell which classes in a file do not exist in a target schema
and (b) resolve subtypes ("IfcWall" also matches IfcWallStandardCase).

Run: python3 tools/build_schema_data.py > schema-data.js
"""
import json
import ifcopenshell

OUT = {}
for key, name in (("IFC2X3", "IFC2X3"), ("IFC4", "IFC4"), ("IFC4X3", "IFC4X3_ADD2")):
    schema = ifcopenshell.ifcopenshell_wrapper.schema_by_name(name)
    parents = {}
    for decl in schema.declarations():
        if hasattr(decl, "supertype"):  # entities only
            sup = decl.supertype()
            parents[decl.name()] = sup.name() if sup else ""
    OUT[key] = parents

print("// Generated by tools/build_schema_data.py from ifcopenshell %s. Do not edit." % ifcopenshell.version)
print("// { schema: { EntityName: SupertypeName } }")
print("window.IFC_SCHEMAS = " + json.dumps(OUT, separators=(",", ":"), sort_keys=True) + ";")
